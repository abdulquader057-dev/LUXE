export function parseDbProduct(p: any): Product {
  if (!p) return p;
  
  // Base fields mapping from Supabase DB columns
  const id = p.id;
  const name = p.name;
  let descriptionText = p.description || "";
  const price = Number(p.price || 0);
  const category = p.category || "streetwear";
  const stock = p.stock_quantity !== undefined ? p.stock_quantity : (p.stock !== undefined ? p.stock : 0);
  const discount = p.discount_percentage !== undefined ? p.discount_percentage : (p.discount !== undefined ? p.discount : 0);
  
  // Metadata fields to extract from description JSON or use fallbacks
  let colors: string[] = p.colors || [];
  let sizes: string[] = p.sizes || [];
  let modelImages = p.modelImages || p.model_images || {};
  let images = p.images || (p.image_url ? [p.image_url] : []);
  let ratings = p.ratings || 4.5;
  let reviewsCount = p.reviewsCount || 0;
  let offer = p.offer || "";

  try {
    if (p.description && p.description.startsWith("{")) {
      const meta = JSON.parse(p.description);
      descriptionText = meta.text || meta.description || descriptionText;
      colors = meta.colors || colors;
      sizes = meta.sizes || sizes;
      modelImages = meta.modelImages || meta.model_images || modelImages;
      images = meta.images || images;
      ratings = meta.ratings !== undefined ? meta.ratings : ratings;
      reviewsCount = meta.reviewsCount !== undefined ? meta.reviewsCount : reviewsCount;
      offer = meta.offer || offer;
    }
  } catch (e) {
    console.error("Error parsing product description JSON:", e);
  }

  // Ensure images contain absolute paths pointing to public
  const mappedImages = images.map((img: string) => {
    if (img && !img.startsWith("/") && !img.startsWith("http")) {
      return "/" + img;
    }
    return img;
  });

  return {
    id,
    name,
    description: descriptionText,
    price,
    currency: "INR",
    category,
    images: mappedImages,
    stock,
    discount,
    sizes,
    colors,
    ratings,
    reviewsCount,
    offer,
    modelImages,
    model_url: p.model_url || null,
  };
}
